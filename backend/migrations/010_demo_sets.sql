-- Наборы тестовых учётных записей. ADR 0007, раздел «Тестовый стенд».
--
-- Набор это четыре записи, по одной на роль. На стенде каждый проверяющий
-- берёт свой набор и заводит второй фактор в своём телефоне, не отнимая ключ
-- у соседа. Первый набор создаёт команда `seed`, остальные заводит панель на
-- экране входа при флаге `TEST_STAND`.
--
-- Колонка пустая у настоящих записей. По ней панель и отличает то, что можно
-- удалять, от того, что удалять нельзя.

ALTER TABLE app_user ADD COLUMN demo_set integer;

-- Записи, заведённые прежней командой `seed`, становятся первым набором.
UPDATE app_user SET demo_set = 1 WHERE username IN ('ods', 'district', 'tech', 'crew');

CREATE INDEX app_user_demo_set_idx ON app_user (demo_set) WHERE demo_set IS NOT NULL;
