-- Участок как родитель пикетов. ADR 0018.
--
-- Пожар считается на участке хода около 150 м, а не на пикете: диспетчер
-- отправляет бригаду на участок, а не к одному извещателю. Датчики и их
-- история остаются на пикетах. Пикет знает свой участок, и карточка участка
-- перечисляет датчики всех своих пикетов.

ALTER TABLE facility ADD COLUMN parent_id text;

CREATE INDEX facility_parent_idx ON facility (parent_id) WHERE parent_id IS NOT NULL;
