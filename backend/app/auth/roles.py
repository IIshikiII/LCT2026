"""Роли и права. Таблица данных, а не ветвление по имени роли.

Состав ролей задал заказчик на QA-сессии. Своих ролей мы не
придумывали: пять групп пользователей ТЗ §3 заказчик свёл к трём уровням
видимости, а ментор добавил четвёртую роль для подтверждения факта на объекте.

Роль отвечает на два вопроса, и они независимы.

1. **Что видно.** Область видимости режет выборку в запросе к базе, а не в
   интерфейсе. Скрытая строка, которую отдаёт API, правами не является.
2. **Что можно.** Право называется кодом действия. Список действий карточки
   сервер считает сам, поэтому кнопка без права не доезжает до экрана, а
   эндпоинт действия отказывает кодом 403.

Заказчик отдельно просил не делить права по инженерным системам: тенденции
нужны всем. Поэтому направление в правах не участвует.
"""

from __future__ import annotations

from dataclasses import dataclass

# Вид области видимости. Значение лежит в поле `scope_value` учётной записи.
SCOPE_ALL = "ALL"
SCOPE_DISTRICT = "DISTRICT"
SCOPE_COMPLEX = "COMPLEX"


@dataclass(frozen=True)
class Role:
    code: str
    label: str
    scope_kind: str
    # Коды действий, которые роль имеет право выполнять.
    permissions: frozenset[str]
    # Пояснение для экрана входа и для документации.
    note: str


# Техник читает и ничего не меняет: заказчик назвал его областью видимости, а
# не участником разбора. Диспетчер района и диспетчер ОДС имеют одинаковые
# права и отличаются только шириной обзора. Группа реагирования получает ровно
# одно право: закрыть заявку отметкой о факте.
DISPATCH_ACTIONS = frozenset({"take", "release", "decide", "assign", "reject"})

ROLES: tuple[Role, ...] = (
    Role(
        "TECHNICIAN",
        "Техник",
        SCOPE_COMPLEX,
        frozenset(),
        "Видит один комплекс коллекторов, только чтение",
    ),
    Role(
        "DISTRICT_DISPATCHER",
        "Диспетчер района",
        SCOPE_DISTRICT,
        DISPATCH_ACTIONS,
        "Видит комплексы своего района, разбирает прогнозы и заявки",
    ),
    Role(
        "ODS_DISPATCHER",
        "Диспетчер ОДС",
        SCOPE_ALL,
        DISPATCH_ACTIONS,
        "Видит всё предприятие, разбирает прогнозы и заявки",
    ),
    Role(
        "RESPONSE_TEAM",
        "Группа реагирования",
        SCOPE_ALL,
        frozenset({"close"}),
        "Подтверждает факт на объекте и закрывает заявку",
    ),
)

_BY_CODE = {role.code: role for role in ROLES}


def by_code(code: str) -> Role | None:
    return _BY_CODE.get(code)


def require(code: str) -> Role:
    """Отдаёт роль или падает.

    Роль приходит из базы, и неизвестное значение означает испорченную запись.
    Тихая подстановка роли по умолчанию выдала бы права, которых никто не
    назначал, поэтому здесь исключение, а не запасной вариант.
    """
    role = by_code(code)
    if role is None:
        known = ", ".join(sorted(_BY_CODE))
        raise ValueError(f"роль {code!r} неизвестна, известны: {known}")
    return role
