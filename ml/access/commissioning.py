"""Период ввода объекта в работу. Общий отбор для всех скриптов направления.

## Зачем

Новый объект первые месяцы тревожит не по делу. Монтажники ходят по коллектору,
двери стоят открытыми, пороги датчиков ещё не выставлены. Такая тревога является
шумом пусконаладки, а не проникновением.

Замер по выгрузке. Объект, который работает давно, даёт долю тревог доступа
0,091 % от своих записей. Объект в первый месяц жизни даёт 9,425 %, то есть в
104 раза больше. Дальше доля падает.

| Месяц с первой записи | Доля тревог доступа |
|---|---|
| 0 | 9,425 % |
| 1–8 | от 1,309 % до 2,705 % |
| 9 | 0,761 % |
| 10 | 0,448 % |
| 12 | 0,241 % |
| 13–23 | от 0,102 % до 0,439 % |

## Почему 270 суток

Граница выбрана по замеру на отрезках обучения, а не по круглому числу. База
проверочного отрезка перестаёт меняться на 270 сутках и дальше стоит на месте.

| Окно | Строк панели | База обучения | База проверки | Проверка к обучению |
|---|---|---|---|---|
| 0 | 2 607 084 | 0,4561 % | 1,2085 % | 2,65 |
| 90 | 2 559 725 | 0,4188 % | 0,9748 % | 2,33 |
| 180 | 2 511 380 | 0,4212 % | 0,5695 % | 1,35 |
| 270 | 2 466 692 | 0,4260 % | 0,4091 % | 0,96 |
| 365 | 2 421 947 | 0,4320 % | 0,4091 % | 0,95 |
| 540 | 2 347 265 | 0,4386 % | 0,4091 % | 0,93 |

Окно в 270 суток убирает 5,4 % строк панели и сводит базы обучения и проверки.
Окно шире отнимает данные и ничего не даёт.

## Чего правило не закрывает

Правило закрывает ввод объекта в работу. Артефакт миграции 2021 года оно не
закрывает: объект 5343 даёт тогда 1 035 653 записи «Неисправен» при доле
доступа 0,791 %. Это отказ датчика, а не доступ. Тот артефакт остаётся
поимённым отбором и относится к направлению `SENSOR_FAILURE`.

## Левый край выгрузки

Объект, который пишет с первого дня выгрузки, ввода в работу не показывает: мы
не видим его начала. Такой объект правило пропускает целиком. Граница левого
края равна 2019-01-31.
"""

from __future__ import annotations

# Сутки от первой записи объекта, которые выбывают из выборки.
WINDOW_DAYS = 270

# Объект с первой записью до этой даты наблюдается с левого края выгрузки.
# Его ввод в работу лежит раньше выгрузки, поэтому правило его не трогает.
DUMP_START = "2019-01-31"


def table_sql(events: str, channels: str, name: str = "commissioning") -> str:
    """Возвращает `CREATE TABLE`, который считает дату готовности объекта.

    Таблица держит три колонки: `object_id`, `first_day` и `ready_day`. Строка
    выборки проходит отбор, когда её день не меньше `ready_day`.
    """
    return f"""
    CREATE OR REPLACE TABLE {name} AS
    SELECT
        ch.oid AS object_id,
        min(ev.d) AS first_day,
        CASE
            WHEN min(ev.d) <= DATE '{DUMP_START}' THEN DATE '1900-01-01'
            ELSE min(ev.d) + INTERVAL {WINDOW_DAYS} DAY
        END AS ready_day
    FROM read_parquet('{events}') ev
    JOIN read_parquet('{channels}') ch ON ch.cid = ev.channel_id
    GROUP BY 1
    """
